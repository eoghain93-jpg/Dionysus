import { useState, useEffect, useRef, useId } from 'react'
import { X } from '../../lib/icons'
import { upsertMember } from '../../lib/members'

const TIERS = ['member', 'staff']

/**
 * Modal for adding or editing a member.
 * Props:
 *   member   — null for new member, object for editing
 *   onClose  — called to close the modal
 *   onSaved  — called after successful save
 */
export default function MemberFormModal({ member, onClose, onSaved }) {
  const isEditing = member != null
  const titleId = useId()
  const firstInputRef = useRef(null)
  const overlayRef = useRef(null)

  const favouriteDrinksInitial = Array.isArray(member?.favourite_drinks)
    ? member.favourite_drinks.join(', ')
    : member?.favourite_drinks ?? ''

  const [form, setForm] = useState({
    name: member?.name ?? '',
    membership_number: member?.membership_number ?? '',
    phone: member?.phone ?? '',
    email: member?.email ?? '',
    membership_tier: member?.membership_tier ?? 'member',
    renewal_date: member?.renewal_date ?? '',
    notes: member?.notes ?? '',
    favourite_drinks: favouriteDrinksInitial,
  })
  const [saving, setSaving] = useState(false)
  const [error, setError] = useState(null)

  useEffect(() => {
    firstInputRef.current?.focus()
  }, [])

  useEffect(() => {
    function handleKey(e) {
      if (e.key === 'Escape') onClose()
    }
    document.addEventListener('keydown', handleKey)
    return () => document.removeEventListener('keydown', handleKey)
  }, [onClose])

  function handleOverlayClick(e) {
    if (e.target === overlayRef.current) onClose()
  }

  function handleChange(field) {
    return e => setForm(prev => ({ ...prev, [field]: e.target.value }))
  }

  async function handleSubmit(e) {
    e.preventDefault()
    setSaving(true)
    setError(null)
    try {
      const drinksArray = form.favourite_drinks
        .split(',')
        .map(d => d.trim())
        .filter(Boolean)

      const payload = {
        ...(isEditing ? { id: member.id } : {}),
        name: form.name.trim(),
        membership_number: form.membership_number.trim(),
        phone: form.phone.trim() || null,
        email: form.email.trim() || null,
        membership_tier: form.membership_tier,
        renewal_date: form.renewal_date || null,
        notes: form.notes.trim() || null,
        favourite_drinks: drinksArray.length > 0 ? drinksArray : null,
        active: true,
      }

      // Remove empty membership_number for new members (auto-generated by upsertMember)
      if (!isEditing && !payload.membership_number) {
        delete payload.membership_number
      }

      await upsertMember(payload)
      onSaved()
    } catch (err) {
      setError(err.message ?? 'An error occurred. Please try again.')
      setSaving(false)
    }
  }

  const optional = 'text-slate-400 font-normal'

  return (
    <div
      ref={overlayRef}
      className="ui-modal-backdrop"
      onClick={handleOverlayClick}
      aria-hidden="false"
    >
      <div
        role="dialog"
        aria-modal="true"
        aria-labelledby={titleId}
        className="ui-modal max-w-xl"
      >
        {/* Header */}
        <div className="flex items-center justify-between gap-3">
          <h2
            id={titleId}
            className="ui-modal-title"
          >
            {isEditing ? 'Edit Member' : 'Add Member'}
          </h2>
          <button
            onClick={onClose}
            aria-label="Close modal"
            className="ui-btn ui-btn-ghost ui-btn-icon shrink-0"
          >
            <X size={22} aria-hidden="true" />
          </button>
        </div>

        {/* Form */}
        <form onSubmit={handleSubmit} className="flex flex-col gap-3">
          {error && (
            <p role="alert" className="ui-banner ui-banner-bad">
              {error}
            </p>
          )}

          {/* Name */}
          <div>
            <label htmlFor="mf-name" className="ui-label">
              Name <span aria-hidden="true">*</span>
            </label>
            <input
              ref={firstInputRef}
              id="mf-name"
              type="text"
              required
              value={form.name}
              onChange={handleChange('name')}
              placeholder="Full name"
              className="ui-input"
            />
          </div>

          {/* Membership number */}
          <div>
            <label htmlFor="mf-membership-number" className="ui-label">
              Membership Number{!isEditing && <span className={optional}> (auto-generated if blank)</span>}
              {isEditing && <span aria-hidden="true"> *</span>}
            </label>
            <input
              id="mf-membership-number"
              type="text"
              required={isEditing}
              value={form.membership_number}
              onChange={handleChange('membership_number')}
              placeholder="e.g. M0001"
              className="ui-input"
            />
          </div>

          {/* Phone + Email */}
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            <div>
              <label htmlFor="mf-phone" className="ui-label">
                Phone <span className={optional}>(optional)</span>
              </label>
              <input
                id="mf-phone"
                type="tel"
                value={form.phone}
                onChange={handleChange('phone')}
                placeholder="07700 000000"
                className="ui-input"
              />
            </div>
            <div>
              <label htmlFor="mf-email" className="ui-label">
                Email <span className={optional}>(optional)</span>
              </label>
              <input
                id="mf-email"
                type="email"
                value={form.email}
                onChange={handleChange('email')}
                placeholder="name@example.com"
                className="ui-input"
              />
            </div>
          </div>

          {/* Tier + Renewal date */}
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            <div>
              <label htmlFor="mf-tier" className="ui-label">
                Membership Tier <span aria-hidden="true">*</span>
              </label>
              <select
                id="mf-tier"
                required
                value={form.membership_tier}
                onChange={handleChange('membership_tier')}
                className="ui-select w-full capitalize"
              >
                {TIERS.map(t => (
                  <option key={t} value={t} className="capitalize">{t}</option>
                ))}
              </select>
            </div>
            <div>
              <label htmlFor="mf-renewal-date" className="ui-label">
                Renewal Date <span className={optional}>(optional)</span>
              </label>
              <input
                id="mf-renewal-date"
                type="date"
                value={form.renewal_date}
                onChange={handleChange('renewal_date')}
                className="ui-input cursor-pointer [color-scheme:dark]"
              />
            </div>
          </div>

          {/* Favourite drinks */}
          <div>
            <label htmlFor="mf-favourite-drinks" className="ui-label">
              Favourite Drinks <span className={optional}>(comma-separated, optional)</span>
            </label>
            <input
              id="mf-favourite-drinks"
              type="text"
              value={form.favourite_drinks}
              onChange={handleChange('favourite_drinks')}
              placeholder="Guinness, Jameson, Coke"
              className="ui-input"
            />
          </div>

          {/* Notes */}
          <div>
            <label htmlFor="mf-notes" className="ui-label">
              Notes <span className={optional}>(optional)</span>
            </label>
            <textarea
              id="mf-notes"
              rows={2}
              value={form.notes}
              onChange={handleChange('notes')}
              placeholder="Any additional notes…"
              className="ui-input py-3 resize-none"
            />
          </div>

          {/* Actions */}
          <div className="ui-modal-actions">
            <button
              type="button"
              onClick={onClose}
              className="ui-btn ui-btn-ghost ui-btn-lg flex-1"
            >
              Cancel
            </button>
            <button
              type="submit"
              disabled={saving}
              className="ui-btn ui-btn-primary ui-btn-lg flex-1"
            >
              {saving ? 'Saving…' : isEditing ? 'Save Changes' : 'Add Member'}
            </button>
          </div>
        </form>
      </div>
    </div>
  )
}
